/**
 * Seeds historical lab bookings:
 *  - Pentacam cornea scans (بنتكام) — 228 rows, seq P-336 → P-563
 *  - Radiology / imaging   (اشاعات) — 267 rows, seq P-564 → P-830
 *
 * Accounting posted inline:
 *  - All entries  : Dr 1010 / Cr 4020 (Labs Revenue)
 *  - Radiology dr_share > 0: Dr 5130 / Cr 2010 (Doctor dues accrual)
 *
 * Idempotent: skips file_no that already exists.
 */
class HistoricalLabsBookingsSeeder extends Seeder
{
    use NormalizesArabic;

    public function run(): void
    {
        $adminId = User::min('id');
        $doctors = $this->loadDoctors();
        $bookingAction = app(AutoPostBookingPaymentAction::class);
        $doctorAction = app(AutoPostDoctorDuesAction::class);

        $created = 0;
        $skipped = 0;

        // ── Pentacam ───────────────────────────────────────────────────────
        foreach ($this->getPentacamData() as $row) {
            if (Booking::where('file_no', $row['file_no'])->exists()) {
                $skipped++;

                continue;
            }

            $doctor = $doctors[$row['doctor_name']] ?? $doctors[$this->normalizeArabic($row['doctor_name'])] ?? null;

            /** @var Booking $booking */
            $booking = Booking::create([
                'file_no' => $row['file_no'],
                'patient_name' => $row['patient_name'],
                'patient_phone' => $row['patient_phone'],
                'patient_age' => $row['patient_age'],
                'national_id' => $row['national_id'],
                'gender' => 'unknown',
                'dept' => Department::Labs,
                'service_name' => $row['service_name'],
                'doctor_id' => $doctor?->id,
                'visit_date' => $row['visit_date'],
                'visit_time' => '10:00',
                'price' => $row['price'],
                'discount' => 0,
                'ins_amount' => 0,
                'paid_amount' => $row['paid_amount'],
                'pay_method' => PayMethod::Cash,
                'pay_status' => PayStatus::Paid,
                'status' => CompletedState::$name,
                'analysis_type' => 'بنتاكام',
                'visit_note' => isset($row['address']) ? 'العنوان: '.$row['address'] : null,
                'created_by' => $adminId,
            ]);

            // Dr 1010 (Cash) / Cr 4020 (Labs Revenue)
            $bookingAction->execute($booking);

            $created++;
        }

        $this->command->line("  ✓ Labs (Pentacam): {$created} created, {$skipped} skipped");

        $created = 0;
        $skipped = 0;

        // ── Radiology ─────────────────────────────────────────────────────
        foreach ($this->getRadiologyData() as $row) {
            if (Booking::where('file_no', $row['file_no'])->exists()) {
                $skipped++;

                continue;
            }

            $doctor = $doctors[$row['doctor_name']] ?? $doctors[$this->normalizeArabic($row['doctor_name'])] ?? null;
            $eyeSide = EyeSide::tryFrom($row['eye_side'] ?? 'OU') ?? EyeSide::OU;
            $drShare = (float) ($row['dr_share'] ?? 0);

            /** @var Booking $booking */
            $booking = Booking::create([
                'file_no' => $row['file_no'],
                'patient_name' => $row['patient_name'],
                'patient_phone' => $row['patient_phone'],
                'patient_age' => $row['patient_age'],
                'national_id' => $row['national_id'],
                'gender' => 'unknown',
                'dept' => Department::Labs,
                'service_name' => $row['service_name'],
                'doctor_id' => $doctor?->id,
                'visit_date' => $row['visit_date'],
                'visit_time' => '10:00',
                'price' => $row['price'],
                'discount' => 0,
                'ins_amount' => 0,
                'paid_amount' => $row['paid_amount'],
                'pay_method' => PayMethod::Cash,
                'pay_status' => PayStatus::Paid,
                'status' => CompletedState::$name,
                'eye_side' => $eyeSide,
                'analysis_type' => 'أشعة',
                'visit_note' => isset($row['address']) ? 'العنوان: '.$row['address'] : null,
                'created_by' => $adminId,
            ]);

            // Dr 1010 (Cash) / Cr 4020 (Labs Revenue)
            $bookingAction->execute($booking);

            // Dr 5130 / Cr 2010  (Doctor dues accrual for radiology)
            if ($drShare > 0 && $doctor) {
                $doctorAction->execute(
                    dept: Department::Labs,
                    amount: $drShare,
                    doctorName: $doctor->name,
                    reference: $row['file_no'],
                    date: $row['visit_date'],
                    idempotencyKey: "doctor_dues_hist:{$row['file_no']}",
                );
            }

            $created++;
        }

        $this->command->line("  ✓ Labs (Radiology): {$created} created, {$skipped} skipped");
    }

    /** @return array<string, Doctor> */
    private function loadDoctors(): array
    {
        $map = [];
        foreach (Doctor::all() as $doc) {
            $map[$this->normalizeArabic($doc->name)] = $doc;
        }

        $keyed = [];
        foreach (HistoricalDoctorsSeeder::DOCTORS as $key => $data) {
            $doc = $map[$this->normalizeArabic($data['name'])] ?? null;
            if ($doc) {
                $keyed[$key] = $doc;
                $keyed[$this->normalizeArabic($key)] = $doc;
            }
        }

        return $keyed;
    }

